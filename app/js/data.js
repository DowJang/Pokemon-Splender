function build(rows, tier) {
  return rows.map(([mon, vp, cost], i) => {
    const d = DEX[mon];
    return {
      id: `${tier}-${i}`,
      tier,                                  // 1 | 2 | 3 | 'R' | 'L'
      mon,
      label: d.label || mon,
      dex: d.dex,
      color: d.c,                            // 보너스 색
      bonus: tier === 'R' || tier === 'L' ? 2 : 1,
      vp,
      cost,
      to: d.to || null,                      // 다음 진화 단계
      need: d.need || null,                  // 진화 조건 (카드 보너스)
    };
  });
}

